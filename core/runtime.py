#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
core/runtime.py
===============
حالة تشغيل عامة للتطبيق (وضع المعاينة الجافة dry-run حالياً).

لماذا ملف جديد في core/؟ قواعد المشروع تطلب وضع --dry-run عالمياً
من المكوّن الأساسي. طبقة privilege.py هي نقطة المرور الإجبارية
الوحيدة لكل أمر مرتفع الصلاحية، وعلم عام صغير هنا يسمح لـ
privilege.py وللواجهة وللوحدات قراءة نفس الحالة دون تبعيات دائرية
(هذا الملف لا يستورد شيئاً منها).

الضمانات عندما يكون الوضع مفعّلاً (ثلاث طبقات):
  1) privilege.run_privileged() لا ينفّذ الأمر إطلاقاً ويعيد نتيجة
     موسومة [DRY-RUN] — طبقة أمان أخيرة حتى لو تجاهلت وحدةٌ العلم.
  2) الواجهة تعطّل زر «تطبيق» في كل البطاقات وتعرض شريط تحذير.
  3) الوحدات تستدعي is_dry_run() في apply() وتُرجع رسالة صادقة
     (ما كان سيُنفَّذ) بدل أي تنفيذ — راجع modules/boot_guard.py
     كنموذج مرجعي للوحدات الجديدة.
"""

from __future__ import annotations

_DRY_RUN = False


def set_dry_run(enabled: bool) -> None:
    """يضبط وضع المعاينة الجافة عالمياً (يستدعيه سكربت الدخول عند
    تمرير --dry-run، واختبارات pytest لإدارة الحالة)."""
    global _DRY_RUN
    _DRY_RUN = bool(enabled)


def is_dry_run() -> bool:
    """هل نعمل حالياً في وضع المعاينة الجافة (بلا أي تنفيذ)؟"""
    return _DRY_RUN
